export function getLocalizedGame(
  game: GameDefinition,
  t: (key: string, params?: Record<string, string | number>) => string
): GameDefinition {
  const camelId = game.id.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  const titleKey = `games.${camelId}Title`;
  const descKey = `games.${camelId}Desc`;
  const instructionKey = `games.${camelId}Instruction`;
  const skillKey = `games.${camelId}Skill`;

  const title = t(titleKey);
  const shortDescription = t(descKey);
  const detailedInstructions = t(instructionKey);
  const skillLabel = t(skillKey);

  return {
    ...game,
    title: title && title !== titleKey ? title : game.title,
    shortDescription: shortDescription && shortDescription !== descKey ? shortDescription : game.shortDescription,
    detailedInstructions: detailedInstructions && detailedInstructions !== instructionKey ? detailedInstructions : game.detailedInstructions,
    skillLabel: skillLabel && skillLabel !== skillKey ? skillLabel : game.skillLabel,
  };
}
